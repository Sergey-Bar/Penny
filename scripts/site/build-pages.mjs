// Builds the website's generated pages, in Hebrew and English, from the content files in scripts/site/content:
//   features-*.mjs  ->  feature-<slug>.html          one page per feature
//   guides.mjs      ->  guide-<slug>.html, guides.html
//   compare.mjs     ->  compare-<slug>.html, compare.html   (the table is compare-sections.<lang>.partial)
//   help.mjs        ->  help.html
// The top bar, footer, icons and card texts are taken from features.html, so that page stays the one place they are
// edited by hand. Also points the menus, the footer and the cards at every feature page that exists.
// Safe to run again:  npm run site:build
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.join(HERE, "../../website");
const CONTENT = path.join(HERE, "content");
const ORIGIN = "https://sergey-bar.github.io/Penny/";
const DEMO = "https://penny-finance-demo.vercel.app";
const NOTE = `<!-- Generated by scripts/site/build-pages.mjs from scripts/site/content. Edit those, not this file. -->\n`;

const load = async (name) => (await import(pathToFileURL(path.join(CONTENT, name)).href)).default;
const features = (
  await Promise.all(
    fs
      .readdirSync(CONTENT)
      .filter((f) => /^features-.*\.mjs$/.test(f))
      .sort()
      .map(load),
  )
).flat();
const guides = await load("guides.mjs");
const compare = await load("compare.mjs");
const help = await load("help.mjs");

const LANGS = {
  he: {
    dir: "",
    up: "",
    arrow: "←",
    features: "פיצ'רים",
    guides: "מדריכים",
    compare: "השוואות",
    crumbs: "מיקום באתר",
    tryIt: "לנסות בדפדפן",
    tryScreen: "לפתוח את המסך הזה בדפדפן",
    know: "טוב לדעת",
    faq: "שאלות ותשובות",
    related: "פיצ'רים קשורים",
    used: "הפיצ'רים שבמדריך",
    more: "לדף המלא",
    moreGuides: "לכל המדריכים",
    feature: "יכולת",
    fullTable: "לטבלת ההשוואה המלאה, מול כל המוצרים",
    otherCompare: "השוואות נוספות",
    vs: "מול",
    guidesIndex: {
      title: "מדריכים",
      desc: "מדריכים צעד אחר צעד ל-Penny: חיבור בנק ראשון, מעבר מ-Excel, תקציב משפחתי, דוח הפנסיה, גיבוי וחיבור בוט הטלגרם.",
      h1: "מדריכים, צעד אחר צעד.",
      lead: "כל מדריך עונה על שאלה אחת, מההתחלה ועד הסוף, עם הצעדים לפי הסדר.",
    },
  },
  en: {
    dir: "en/",
    up: "../",
    arrow: "→",
    features: "Features",
    guides: "Guides",
    compare: "Compare",
    crumbs: "Breadcrumb",
    tryIt: "Try it in your browser",
    tryScreen: "Open this screen in your browser",
    know: "Good to know",
    faq: "Questions and answers",
    related: "Related features",
    used: "Features used in this guide",
    more: "Full page",
    moreGuides: "All guides",
    feature: "Capability",
    fullTable: "The full comparison table, against every product",
    otherCompare: "More comparisons",
    vs: "vs",
    guidesIndex: {
      title: "Guides",
      desc: "Step-by-step guides to Penny: your first bank, moving from Excel, a family budget, the pension report, backup and the Telegram bot.",
      h1: "Guides, step by step.",
      lead: "Each guide answers one question from start to finish, with the steps in order.",
    },
  },
};

const read = (f) => fs.readFileSync(path.join(SITE, f), "utf8").replace(/\r\n/g, "\n");
// Keep each file's own line endings, so a rebuild doesn't rewrite every line.
const write = (f, text) => {
  const full = path.join(SITE, f);
  const crlf = fs.existsSync(full) ? fs.readFileSync(full, "utf8").includes("\r\n") : true;
  fs.writeFileSync(full, crlf ? text.replace(/\r?\n/g, "\r\n") : text.replace(/\r\n/g, "\n"));
};
const grab = (text, re, what) => {
  const m = text.match(re);
  if (!m) throw new Error(`build-pages: ${what} not found`);
  return m;
};
// Text only. Walks the characters and drops everything between < and >, and the brackets themselves.
const plain = (html) =>
  [...html]
    .reduce(
      (s, ch) =>
        ch === "<"
          ? { ...s, tag: true }
          : ch === ">"
            ? { ...s, tag: false }
            : s.tag
              ? s
              : { ...s, out: s.out + ch },
      { out: "", tag: false },
    )
    .out.replace(/&amp;/g, "&")
    .replace(/‏/g, "");
// JSON that sits inside a <script> element must not be able to close it.
const jsonLd = (data) => JSON.stringify(data).replace(/</g, "\\u003c");
const featureFile = (p) => `feature-${p.slug}.html`;
const featureById = Object.fromEntries(features.map((p) => [p.id, p]));
const built = [];

for (const [lang, t] of Object.entries(LANGS)) {
  // ---- point menus, footers and cards at the feature pages that exist ----
  for (const name of ["index.html", "features.html", "install.html"]) {
    let h = read(t.dir + name);
    for (const p of features) {
      h = h.replaceAll(`href="features.html#f-${p.id}"`, `href="${featureFile(p)}"`);
      if (name !== "features.html") continue;
      h = h.replace(
        new RegExp(`(<nav class="feat-index"[\\s\\S]*?)href="#f-${p.id}"`),
        `$1href="${featureFile(p)}"`,
      );
      const card = grab(
        h,
        new RegExp(`<article class="feat[^"]*" id="f-${p.id}">.*</article>`),
        `card f-${p.id}`,
      )[0];
      if (!card.includes("feat-more"))
        h = h.replace(
          card,
          card.replace(
            "</article>",
            `<a class="feat-more" href="${featureFile(p)}">${t.more} <span aria-hidden="true">${t.arrow}</span></a></article>`,
          ),
        );
    }
    write(t.dir + name, h);
  }

  // ---- pieces borrowed from the hand-written pages ----
  const feat = read(t.dir + "features.html");
  const home = read(t.dir + "index.html");
  const head = feat.slice(0, feat.indexOf("</head>"));
  const chrome = grab(feat, /<a class="skip"[\s\S]*?<\/header>\n/, "top bar")[0].replace(
    / aria-current="page"/g,
    "",
  );
  const footer = grab(feat, /<footer>[\s\S]*?<\/footer>\n/, "footer")[0];
  const closing = grab(
    feat,
    /  <section class="closing">[\s\S]*?<\/section>\n/,
    "closing band",
  )[0].replace('class="closing"', 'class="closing tint"');
  const dlBtn = grab(
    chrome,
    /<a class="btn btn-primary cta-btn"[^>]*data-dl[^>]*>[^<]*<\/a>/,
    "download button",
  )[0].replace(" cta-btn", "");
  const cards = Object.fromEntries(
    [
      ...feat.matchAll(
        /<article class="feat[^"]*" id="f-([a-z]+)"><div class="glyph" aria-hidden="true">(<svg.*?<\/svg>)<\/div><h3>(.*?)(?:<span class="badge.*?<\/span>)?<\/h3><p>(.*?)<\/p>/g,
      ),
    ].map((m) => [m[1], { icon: m[2], title: m[3], blurb: m[4] }]),
  );
  const EMBED = {
    banks: () => grab(feat, /<ul class="chips"[\s\S]*?<\/ul>/, "bank chips")[0],
    houses: () => grab(feat, /<ul class="houses"[\s\S]*?<\/ul>/, "pension houses")[0],
    chat: () => grab(home, /<figure class="chat"[\s\S]*?<\/figure>/, "telegram chat")[0],
    ledger: () => grab(home, /<ul class="ledger">[\s\S]*?<\/ul>/, "privacy ledger")[0],
  };
  const INLINE = new Set(["banks", "houses"]); // these sit under the text; the others stand beside it

  // One page: the shared head, top bar and footer around `body`. `current` marks the section in the top bar.
  const shell = ({ file, title, desc, body, ld, current }) => {
    const pageHead = head
      .replace(/<title>.*<\/title>/, `<title>${plain(title)} · Penny</title>`)
      .replace(/(<meta name="description" content=")[^"]*/, `$1${plain(desc)}`)
      .replace(/(<meta property="og:title" content=")[^"]*/, `$1${plain(title)} · Penny`)
      .replace(/(<meta property="og:description" content=")[^"]*/, `$1${plain(desc)}`)
      .replace(/Penny\/((?:en\/)?)features\.html"/g, `Penny/$1${file}"`);
    let bar = chrome.replace(/features\.html" hreflang/g, `${file}" hreflang`);
    if (current === "features") bar = bar.replace("<summary>", '<summary aria-current="page">');
    else if (current)
      bar = bar.replace(
        `<li><a href="${current}">`,
        `<li><a href="${current}" aria-current="page">`,
      );
    built.push(file);
    write(
      t.dir + file,
      pageHead +
        (ld ? `<script type="application/ld+json">${jsonLd(ld)}</script>\n` : "") +
        `</head>\n<body>\n${bar}\n${NOTE}<main id="main">\n${body}</main>\n\n${footer}\n` +
        `<script type="module" src="${t.up}theme.js"></script>\n<script type="module" src="${t.up}site.js"></script>\n<script type="module" src="${t.up}os-lead.js"></script>\n</body>\n</html>\n`,
    );
  };
  const crumbs = (parentHref, parent, here) =>
    `      <nav class="crumbs" aria-label="${t.crumbs}"><a href="${parentHref}">${parent}</a><span aria-hidden="true">/</span><span aria-current="page">${here}</span></nav>\n`;
  const pageHead = (crumb, h1, lead, cta = "") =>
    `  <div class="page-head">\n    <div class="wrap">\n${crumb}      <h1>${h1}</h1>\n      <p class="lead">${lead}</p>\n${cta}    </div>\n  </div>\n\n`;
  const shotTag = (s) => {
    const src = `${t.up}${path.posix.dirname(s.shot)}/${lang}/${path.posix.basename(s.shot)}.webp`;
    if (
      !fs.existsSync(
        path.join(SITE, path.posix.dirname(s.shot), lang, path.posix.basename(s.shot) + ".webp"),
      )
    )
      throw new Error(`build-pages: no screenshot ${s.shot} for ${lang}`);
    return `<a class="shot" href="${src}"><img src="${src}" width="1440" height="900" alt="${s.alt ?? ""}" loading="lazy" decoding="async"></a>`;
  };
  // Numbered sections: text, an optional list, and a screenshot or a block borrowed from the site beside it.
  const steps = (sections) => {
    let flip = false;
    return (
      sections
        .map((s, i) => {
          const inline = s.embed && INLINE.has(s.embed) ? "\n        " + EMBED[s.embed]() : "";
          const visual =
            s.embed && !INLINE.has(s.embed) ? EMBED[s.embed]() : s.shot ? shotTag(s) : "";
          const copy =
            `<div class="copy">\n        <span class="num" aria-hidden="true">${String(i + 1).padStart(2, "0")}</span>\n        <h2>${s.h}</h2>\n        <p>${s.p}</p>` +
            (s.list
              ? `\n        <ul class="ticks">${s.list.map((x) => `<li>${x}</li>`).join("")}</ul>`
              : "") +
            inline +
            `\n      </div>`;
          const cls = visual ? `wrap spread${(flip = !flip) ? "" : " flip"}` : "wrap narrow";
          return `  <section class="step${i % 2 ? "" : " tint"}">\n    <div class="${cls}">\n      ${copy}${visual ? "\n      " + visual : ""}\n    </div>\n  </section>\n`;
        })
        .join("\n") + "\n"
    );
  };
  const know = (items) =>
    items?.length
      ? `  <section id="know">\n    <div class="wrap narrow">\n      <h2>${t.know}</h2>\n      <ul class="ticks">${items.map((x) => `<li>${x}</li>`).join("")}</ul>\n    </div>\n  </section>\n\n`
      : "";
  const faq = (items) =>
    items?.length
      ? `  <section id="faq" class="tint">\n    <div class="wrap narrow">\n      <h2>${t.faq}</h2>\n      <div class="faq">\n` +
        items
          .map(([q, a]) => `        <details><summary>${q}</summary><p>${a}</p></details>\n`)
          .join("") +
        `      </div>\n    </div>\n  </section>\n\n`
      : "";
  const faqLd = (file, items) =>
    items?.length && {
      "@context": "https://schema.org",
      "@type": "FAQPage",
      inLanguage: lang,
      url: ORIGIN + t.dir + file,
      mainEntity: items.map(([q, a]) => ({
        "@type": "Question",
        name: q,
        acceptedAnswer: { "@type": "Answer", text: plain(a) },
      })),
    };
  const featureCards = (title, ids, where) =>
    `  <section id="related">\n    <div class="wrap">\n      <div class="head">\n        <h2>${title}</h2>\n      </div>\n      <div class="feat-grid">\n` +
    ids
      .map((id) => {
        const r = cards[id];
        if (!r) throw new Error(`build-pages: ${where} relates to unknown card ${id}`);
        const href = featureById[id] ? featureFile(featureById[id]) : `features.html#f-${id}`;
        return `        <a class="feat" href="${href}"><div class="glyph" aria-hidden="true">${r.icon}</div><h3>${r.title}</h3><p>${r.blurb}</p></a>\n`;
      })
      .join("") +
    `      </div>\n    </div>\n  </section>\n\n`;
  const linkCards = (items) =>
    `      <div class="feat-grid">\n` +
    items
      .map(
        ([href, title, text]) =>
          `        <a class="feat" href="${href}"><h3>${title}</h3><p>${text}</p></a>\n`,
      )
      .join("") +
    `      </div>\n`;

  // ---- feature pages ----
  for (const p of features) {
    const c = p[lang];
    const card = cards[p.id];
    if (!card) throw new Error(`build-pages: no card f-${p.id} in ${t.dir}features.html`);
    const file = featureFile(p);
    const cta = `      <div class="cta">${dlBtn}<a class="btn btn-ghost" href="${DEMO}${p.demo ?? ""}">${p.demo ? t.tryScreen : t.tryIt}</a></div>\n`;
    shell({
      file,
      title: card.title,
      desc: c.desc,
      current: "features",
      ld: faqLd(file, c.faq),
      body:
        pageHead(crumbs("features.html", t.features, card.title), c.h1, c.intro, cta) +
        steps(c.sections) +
        know(c.know) +
        faq(c.faq) +
        featureCards(t.related, p.related, p.slug) +
        closing,
    });
  }

  // ---- guides ----
  for (const p of guides) {
    const c = p[lang];
    const file = `guide-${p.slug}.html`;
    shell({
      file,
      title: c.title,
      desc: c.desc,
      current: "guides.html",
      ld: faqLd(file, c.faq),
      body:
        pageHead(crumbs("guides.html", t.guides, c.title), c.h1, c.intro) +
        steps(c.sections) +
        know(c.know) +
        faq(c.faq) +
        featureCards(t.used, p.related, p.slug) +
        closing,
    });
  }
  const gi = t.guidesIndex;
  shell({
    file: "guides.html",
    title: gi.title,
    desc: gi.desc,
    current: "guides.html",
    body:
      pageHead("", gi.h1, gi.lead) +
      `  <section class="tint">\n    <div class="wrap">\n` +
      linkCards(guides.map((p) => [`guide-${p.slug}.html`, p[lang].h1, p[lang].desc])) +
      `    </div>\n  </section>\n\n` +
      closing.replace(' tint"', '"'),
  });

  // ---- comparisons: Penny's column and one other, cut from the table on the home page ----
  const partial = fs
    .readFileSync(path.join(CONTENT, `compare-sections.${lang}.partial`), "utf8")
    .replace(/\r\n/g, "\n");
  const table = grab(partial, /<table>[\s\S]*?<\/table>/, "comparison table")[0];
  const heads = [
    ...grab(table, /<thead>[\s\S]*?<\/thead>/, "table head")[0].matchAll(
      /<th[^>]*>([\s\S]*?)<\/th>/g,
    ),
  ].map((m) => plain(m[1]).trim());
  const rows = [...table.matchAll(/<tr><th scope="row">(.*?)<\/th>(.*?)<\/tr>/g)].map((m) => [
    m[1],
    [...m[2].matchAll(/<td>(.*?)<\/td>/g)].map((x) => x[1]),
  ]);
  const sources = grab(partial, /<p class="note">[\s\S]*?<\/p>/, "comparison sources")[0];
  for (const p of compare.pages) {
    const c = p[lang];
    const col = heads.indexOf(p.column[lang]) - 1; // heads[0] is the row-label column
    if (col < 1)
      throw new Error(
        `build-pages: no comparison column "${p.column[lang]}" in ${t.dir}index.html`,
      );
    const file = `compare-${p.slug}.html`;
    const others = compare.pages
      .filter((o) => o !== p)
      .map((o) => `<a href="compare-${o.slug}.html">${o.column[lang]}</a>`);
    shell({
      file,
      title: `Penny ${t.vs} ${p.column[lang]}`,
      desc: c.desc,
      current: null,
      body:
        pageHead(crumbs("compare.html", t.compare, p.column[lang]), c.h1, c.intro) +
        `  <section class="tint">\n    <div class="wrap">\n      <div class="compare vs" tabindex="0" role="region" aria-label="${plain(c.h1)}"><table><thead><tr><th scope="col">${t.feature}</th><th scope="col">Penny</th><th scope="col">${p.column[lang]}</th></tr></thead><tbody>` +
        rows
          .map(
            ([label, cells]) =>
              `<tr><th scope="row">${label}</th><td>${cells[0]}</td><td>${cells[col]}</td></tr>`,
          )
          .join("") +
        `</tbody></table></div>\n      ${sources}\n      <div class="choose"><div><h3>${c.usTitle}</h3><p>${c.us}</p></div><div><h3>${c.themTitle}</h3><p>${c.them}</p></div></div>\n` +
        `      <p class="map-more"><a class="btn btn-ghost" href="compare.html#compare">${t.fullTable}</a></p>\n      <p class="more-links">${t.otherCompare}: ${others.join("")}</p>\n    </div>\n  </section>\n\n` +
        closing.replace(' tint"', '"'),
    });
  }
  const ci = compare.index[lang];
  shell({
    file: "compare.html",
    title: ci.title,
    desc: ci.desc,
    current: null,
    body:
      pageHead("", ci.h1, ci.lead) +
      `  <section class="tint">\n    <div class="wrap">\n` +
      linkCards(
        compare.pages.map((p) => [
          `compare-${p.slug}.html`,
          `Penny ${t.vs} ${p.column[lang]}`,
          p[lang].desc,
        ]),
      ) +
      `    </div>\n  </section>\n\n` +
      partial.replace(/      <div class="head">[\s\S]*?      <\/div>\n/, "") +
      "\n" +
      closing.replace(' tint"', '"'),
  });

  // ---- help ----
  const hp = help[lang];
  shell({
    file: "help.html",
    title: hp.title,
    desc: hp.desc,
    current: null,
    body:
      pageHead("", hp.h1, hp.lead) +
      hp.groups
        .map(
          (g, i) =>
            `  <section${i % 2 ? "" : ' class="tint"'}>\n    <div class="wrap">\n      <div class="head">\n        <h2>${g.h}</h2>\n        <p>${g.p}</p>\n      </div>\n` +
            linkCards(g.links) +
            `    </div>\n  </section>\n\n`,
        )
        .join("") +
      closing.replace(' tint"', hp.groups.length % 2 ? '"' : ' tint"'),
  });
}

// ---- sitemap: every generated page, once ----
let map = read("sitemap.xml");
for (const file of new Set(built))
  for (const dir of ["", "en/"]) {
    const loc = `${ORIGIN}${dir}${file}`;
    if (map.includes(`<loc>${loc}</loc>`)) continue;
    const entry = `  <url>\n    <loc>${loc}</loc>\n    <xhtml:link rel="alternate" hreflang="he" href="${ORIGIN}${file}"/>\n    <xhtml:link rel="alternate" hreflang="en" href="${ORIGIN}en/${file}"/>\n  </url>\n`;
    map = map.replace("</urlset>", entry + "</urlset>");
  }
write("sitemap.xml", map);
console.log(
  `Built ${new Set(built).size} pages in 2 languages: ${features.length} features, ${guides.length} guides, ${compare.pages.length} comparisons, help.`,
);
