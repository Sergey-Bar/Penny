/** Canonical English name per key, for the legacy `dictionaryCategory` wrapper. */
const CATEGORY_NAME_BY_KEY: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(SEEDED_CATEGORY_KEYS).map(([name, key]) => [key, name]),
);

export function categoryNameForKey(key: string): string | null {
  return CATEGORY_NAME_BY_KEY[key] ?? null;
}

const byLowerName = new Map<string, string>();
for (const [name, key] of Object.entries(SEEDED_CATEGORY_KEYS)) {
  byLowerName.set(name.trim().toLowerCase(), key);
}
for (const [name, key] of Object.entries(CATEGORY_KEY_HEBREW_ALIASES)) {
  byLowerName.set(name.trim().toLowerCase(), key);
}

/** The built-in key for a category name (English or Hebrew), or null for a household-created one. */
export function categoryKeyForName(name: string | null | undefined): string | null {
  const clean = (name ?? "").trim().toLowerCase();
  return clean ? (byLowerName.get(clean) ?? null) : null;
}

